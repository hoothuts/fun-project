// Generates fallback lore & highlights for any driver across 1950–Present
export function getDriverBio(driverId, driverData) {
  if (driverBios[driverId]) {
    return driverBios[driverId];
  }

  const name = driverData?.driver
    ? `${driverData.driver.givenName} ${driverData.driver.familyName}`
    : driverId.replace(/_/g, ' ').toUpperCase();

  const wins = driverData?.totalWins || 0;
  const podiums = driverData?.podiums || 0;
  const races = driverData?.totalRaces || 0;
  const pts = driverData?.points || 0;
  const nat = driverData?.driver?.nationality || 'International';

  let lore = `${name} competed in Formula 1 across ${races} Grand Prix entries representing ${nat} motorsport on the global championship stage.`;
  let trivia = `Recorded ${races} career Grand Prix entries${pts > 0 ? ` with ${pts} championship points` : ''}${wins > 0 ? ` and ${wins} victories` : podiums > 0 ? ` and ${podiums} podium finishes` : ''}.`;

  if (wins > 0) {
    lore = `A Grand Prix winner in Formula 1, ${name} claimed ${wins} victories and ${podiums} podium finishes across ${races} career starts.`;
  } else if (podiums > 0) {
    lore = `A celebrated Formula 1 podium finisher, ${name} achieved ${podiums} top-three finishes across a ${races}-race career.`;
  }

  return {
    nickname: '',
    titles: 0,
    careerSpan: driverData?.recentResults?.[0]?.season ? `Active in F1` : 'Formula 1 Veteran',
    teams: driverData?.recentResults?.map((r) => r.constructor).filter((v, i, a) => a.indexOf(v) === i) || [],
    lore,
    trivia,
  };
}
